"""Bundle audio analysis JSON into audio/data.js so the renderer can load it from file:// pages."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, "audio")
m = json.load(open(os.path.join(A, "mouth.json")))
w = json.load(open(os.path.join(A, "words.json")))
b = json.load(open(os.path.join(A, "beats.json")))
with open(os.path.join(A, "data.js"), "w") as f:
    f.write("// Generated by tools/export_audio_data.py\nwindow.A=window.A||{};A.MOUTH=" + json.dumps(m, separators=(",", ":")) +
            ";\nA.WORDS=" + json.dumps(w, ensure_ascii=False, separators=(",", ":")) + ";\nA.BEATS=" + json.dumps(b, separators=(",", ":")) + ";\n")
