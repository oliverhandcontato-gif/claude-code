"""5x7 pixel font (hand-authored glyphs) for titles; drawn with a 1px dark outline."""
import numpy as np
from raster import hexc

G = {
    "A": [".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
    "C": [".####", "#....", "#....", "#....", "#....", "#....", ".####"],
    "D": ["####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####."],
    "E": ["#####", "#....", "#....", "####.", "#....", "#....", "#####"],
    "H": ["#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
    "I": ["#####", "..#..", "..#..", "..#..", "..#..", "..#..", "#####"],
    "K": ["#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#"],
    "N": ["#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#", "#...#"],
    "O": [".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
    "P": ["####.", "#...#", "#...#", "####.", "#....", "#....", "#...."],
    "R": ["####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#"],
    "S": [".####", "#....", "#....", ".###.", "....#", "....#", "####."],
    "T": ["#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."],
    "U": ["#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
    "V": ["#...#", "#...#", "#...#", "#...#", ".#.#.", ".#.#.", "..#.."],
    "Z": ["#####", "....#", "...#.", "..#..", ".#...", "#....", "#####"],
    "!": ["..#..", "..#..", "..#..", "..#..", "..#..", ".....", "..#.."],
    " ": [".....", ".....", ".....", ".....", ".....", ".....", "....."],
    "~": [".#.#.", "#.#..", ".....", ".....", ".....", ".....", "....."],
}


def text(fr, s, x, y, col, scale=1, outline="#100810"):
    col = np.array(hexc(col), np.uint8) if isinstance(col, str) else col
    oc = np.array(hexc(outline), np.uint8)
    H, W = fr.shape[:2]
    cx = x
    pix = []
    for ch in s:
        if ch == "Ã":
            g = G["A"]; tilde = True
        else:
            g = G.get(ch, G[" "]); tilde = False
        for j, row in enumerate(g):
            for i, c in enumerate(row):
                if c == "#":
                    pix.append((cx + i * scale, y + j * scale))
        if tilde:
            for (i, j) in ((1, -2), (2, -3), (3, -2), (4, -3)):
                pix.append((cx + i * scale, y + j * scale))
        cx += 6 * scale
    S = set()
    for (px, py) in pix:
        for a in range(scale):
            for b in range(scale):
                S.add((px + a, py + b))
    for (px, py) in S:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                q = (px + dx, py + dy)
                if q not in S and 0 <= q[0] < W and 0 <= q[1] < H:
                    fr[q[1], q[0]] = oc
    for (px, py) in S:
        if 0 <= px < W and 0 <= py < H:
            fr[py, px] = col
    return cx


def width(s, scale=1):
    return len(s) * 6 * scale - scale
